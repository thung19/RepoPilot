from collections import Counter

from repopilot.models import RepositoryAnalysis

LANGUAGE_MAP = {
    ".py": "Python",
    ".js": "JavaScript",
    ".jsx": "JavaScript",
    ".ts": "TypeScript",
    ".tsx": "TypeScript",
    ".java": "Java",
    ".c": "C",
    ".cpp": "C++",
    ".cc": "C++",
    ".go": "Go",
    ".rs": "Rust",
    ".rb": "Ruby",
    ".php": "PHP",
    ".swift": "Swift",
    ".kt": "Kotlin",
    ".cs": "C#",
    ".sh": "Shell",
}

def count_languages(
    analysis: RepositoryAnalysis
) -> dict[str, int]:

    counts = Counter()

    for file in analysis.files:
        language = LANGUAGE_MAP.get(
            file.extension.lower()
        )

        if language is not None:
            counts[language] += 1

    return dict(counts.most_common())


def render_overview(
    analysis: RepositoryAnalysis
) -> str:

    lines = [
        "# Repository Analysis",
        "",
        f"**Repository:** {analysis.name}",
        f"**Discovered files:** {len(analysis.files)}",
        f"**Top-level directories:** {len(analysis.directories)}",
        "",
        "Generated by RepoPilot V0.",
    ]

    return "\n".join(lines)


def render_directories(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## Top-level Directories", ""]

    if not analysis.directories:
        lines.append("No directories discovered.")
    else:
        for directory in analysis.directories:
            lines.append(f"- `{directory}/`")

    return "\n".join(lines)

def render_languages(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## Detected Languages", ""]

    languages = count_languages(analysis)

    if not languages:
        lines.append("No recognized source languages.")
    else:
        lines.extend([
            "| Language | File Count |",
            "| --- | ---: |"
        ])

        for language, count in languages.items():
            lines.append(f"| {language} | {count} |")

    return "\n".join(lines)


def render_dependencies(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## Dependency Manifests", ""]

    if not analysis.dependency_files:
        lines.append("No recognized dependency manifests.")
    else:
        lines.extend([
            "| File | Ecosystem |",
            "| --- | --- |"
        ])

        for dependency in analysis.dependency_files:
            lines.append(
                f"| `{dependency.path}` | "
                f"{dependency.ecosystem} |"
            )

    return "\n".join(lines)


def render_entrypoints(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## Candidate Entry Points", ""]

    if not analysis.entry_points:
        lines.append("No candidate entry points detected.")
    else:
        for entry in analysis.entry_points:
            location = entry.path

            if entry.line_number is not None:
                location += f":{entry.line_number}"

            lines.append(
                f"- `{location}`: {entry.reason}"
            )

    return "\n".join(lines)


def render_readme(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## Repository Documentation", ""]

    if analysis.readme_content is None:
        lines.append("README contents unavailable.")
    else:
        lines.append(
            f"Source: `{analysis.readme_path}`"
        )
        lines.append("")

        for line in analysis.readme_content.splitlines():
            lines.append(f"> {line}")

    return "\n".join(lines)


def render_files(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## File Inventory", ""]

    if not analysis.files:
        lines.append("No files discovered.")
    else:
        for file in analysis.files:
            lines.append(f"- `{file.path}`")

    return "\n".join(lines)

def render_warnings(
    analysis: RepositoryAnalysis
) -> str:

    lines = ["## Warnings and Limitations", ""]

    for warning in analysis.warnings:
        lines.append(f"- {warning}")

    lines.extend([
        "- Entry points are heuristic candidates.",
        "- Dependency versions have not been resolved.",
        "- Repository code has not been executed.",
        "- Setup instructions have not been verified.",
        "- Architecture and data flow have not been inferred."
    ])

    return "\n".join(lines)

def generate_report(
    analysis: RepositoryAnalysis
) -> str:

    sections = [
        render_overview(analysis),
        render_directories(analysis),
        render_languages(analysis),
        render_dependencies(analysis),
        render_entrypoints(analysis),
        render_readme(analysis),
        render_files(analysis),
        render_warnings(analysis),
    ]

    return "\n\n".join(sections) + "\n"