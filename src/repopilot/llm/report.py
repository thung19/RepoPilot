"""Render a validated V1 analysis as a Markdown onboarding guide."""

from repopilot.llm.analyzer import LLMAnalysis
from repopilot.llm.validation import normalize_citation


def clean(text: str) -> str:
    """Collapse whitespace so model text cannot break list formatting."""
    return " ".join(text.split())


class Renderer:
    def __init__(self, result: LLMAnalysis):
        self.result = result
        self.unsupported = {
            issue.location
            for issue in result.issues
            if issue.kind == "unsupported"
        }
        self.needs_check = {
            issue.location
            for issue in result.issues
            if issue.kind in ("bad_line", "missing_reference")
        }
        self.read_files = {d.path for d in result.evidence.documents}

    def sources(self, citations: list[str]) -> str:
        rendered = []

        for citation in citations:
            label = f"`{clean(citation)}`"
            if normalize_citation(citation) not in self.read_files:
                label += " (name only)"
            rendered.append(label)

        return "Sources: " + ", ".join(rendered)

    def flag(self, location: str) -> str:
        if location in self.unsupported:
            return "**[unsupported]** "
        if location in self.needs_check:
            return "**[check]** "
        return ""

    def item_list(self, name: str, items, describe) -> list[str]:
        if not items:
            return ["None identified from the evidence."]

        lines = []
        for index, item in enumerate(items):
            location = f"{name}[{index}]"
            lines.append(f"- {self.flag(location)}{describe(item)}")
            lines.append(f"  {self.sources(item.evidence)}")

        return lines

    def section(self, title: str, name: str, items, describe) -> list[str]:
        return [f"## {title}", ""] + self.item_list(name, items, describe)

    def render(self) -> str:
        result = self.result
        report = result.report
        analysis = result.evidence.analysis

        lines = [
            "# Repository Onboarding Guide",
            "",
            f"**Repository:** {analysis.name}",
            "",
            "Generated by RepoPilot V1: deterministic evidence "
            f"interpreted by `{result.response.model}`. "
            "Review the validation section before relying on it.",
            "",
            "## Purpose",
            "",
            f"{self.flag('purpose')}{clean(report.purpose.statement)}",
            "",
            self.sources(report.purpose.evidence),
            "",
        ]

        lines += self.section(
            "Architecture", "architecture", report.architecture,
            lambda c: f"**{clean(c.name)}**: {clean(c.responsibility)}",
        )
        lines.append("")

        lines += self.section(
            "Entry Points", "entry_points", report.entry_points,
            lambda e: f"`{clean(e.path)}`: {clean(e.description)}",
        )
        lines.append("")

        lines += self.section(
            "Dependencies", "dependencies", report.dependencies,
            lambda d: f"**{clean(d.name)}**: {clean(d.purpose)}",
        )
        lines.append("")

        lines += [
            "## Setup (Unverified)",
            "",
            "> These steps were extracted from repository files and "
            "have not been executed.",
            "",
        ]
        lines += self.item_list(
            "setup_steps", report.setup_steps,
            lambda s: clean(s.instruction),
        )
        lines.append("")

        lines += ["## Unknowns", ""]
        if report.unknowns:
            lines += [f"- {clean(u)}" for u in report.unknowns]
        else:
            lines.append("None reported.")
        lines.append("")

        lines += self.render_validation()
        lines.append("")
        lines += self.render_metadata()

        return "\n".join(lines) + "\n"

    def render_validation(self) -> list[str]:
        lines = ["## Validation", ""]
        issues = self.result.issues

        if not issues:
            lines.append(
                "All citations refer to existing files whose contents "
                "were shown to the model."
            )
        else:
            for issue in issues:
                lines.append(
                    f"- `{issue.location}` ({issue.kind}): "
                    f"{clean(issue.message)}"
                )

        lines += [
            "",
            "Citation checks confirm that files exist and were read. "
            "They do not prove that a claim is correct.",
        ]
        return lines

    def render_metadata(self) -> list[str]:
        evidence = self.result.evidence
        response = self.result.response
        lines = ["## Evidence and Generation", ""]

        read = [d.path for d in evidence.documents]
        lines.append(
            "- Files read: "
            + (", ".join(f"`{p}`" for p in read) if read else "none")
        )

        truncated = [d.path for d in evidence.documents if d.truncated]
        if truncated:
            lines.append(
                "- Truncated: " + ", ".join(f"`{p}`" for p in truncated)
            )

        for note in evidence.omitted:
            lines.append(f"- Not included: {clean(note)}")

        lines.append(f"- Model: `{response.model}`")
        if response.input_tokens is not None:
            lines.append(
                f"- Tokens: {response.input_tokens} in, "
                f"{response.output_tokens} out"
            )
        lines.append(f"- Generation time: {response.duration_seconds:.1f}s")

        return lines


def render_llm_report(result: LLMAnalysis) -> str:
    return Renderer(result).render()
